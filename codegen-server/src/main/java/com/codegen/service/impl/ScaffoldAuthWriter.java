                + "        private final Map<String, RateWindow> apiRateWindows = new ConcurrentHashMap<>();\n\n"
                + "        @Override\n"
                + "        public long tryAcquire(String key, int maxRequests, long windowSeconds) {\n"
                + "            long now = System.currentTimeMillis();\n"
                + "            long windowMs = Math.max(1, windowSeconds) * 1000L;\n"
                + "            // 顺带回收过期窗口，防止 map 无界增长\n"
                + "            if (apiRateWindows.size() > 10_000) {\n"
                + "                apiRateWindows.entrySet().removeIf(e -> now - e.getValue().start >= windowMs);\n"
                + "            }\n"
                + "            RateWindow w = apiRateWindows.compute(key, (k, old) -> {\n"
                + "                if (old == null || now - old.start >= windowMs) {\n"
                + "                    return new RateWindow(now, 1);\n"
                + "                }\n"
                + "                return new RateWindow(old.start, old.count + 1);\n"
                + "            });\n"
                + "            if (w.count <= maxRequests) {\n"
                + "                return 0;\n"
                + "            }\n"
                + "            return Math.max(1, (w.start + windowMs - now) / 1000 + 1);\n"
                + "        }\n"
                + "    }\n\n"
                + "    private record RateWindow(long start, int count) {\n"
                + "    }\n"
                + "}\n";
